"""Build the served town art from the approved source PNGs (docs/04-character-ui-and-art.md, Town art).

    python scripts/town_art.py

Reads docs/assets/town/*.png (never modified) and writes optimized WebP copies to
frontend/public/assets/town/, plus frontend/src/components/town/townArtFiles.ts listing what exists,
so the app only requests images that are there and falls back to its SVG drawings for the rest.
Needs Pillow (pip install pillow).
"""
from __future__ import annotations

from collections import deque
from pathlib import Path

from PIL import Image

ROOT = Path(__file__).resolve().parents[1]
SRC = ROOT / "docs" / "assets" / "town"
OUT = ROOT / "frontend" / "public" / "assets" / "town"
MANIFEST = ROOT / "frontend" / "src" / "components" / "town" / "townArtFiles.ts"

# Longest side of each served image: big enough for a ~1200 px wide scene on a 2x screen, small enough for tablets.
MAX_SIDE = {"town_background": 1600, "scene_background": 1600, "shop": 720, "lumi": 560, "customer": 520, "prop": 256}
QUALITY = 82


def _max_side(stem: str) -> int:
    for prefix, side in MAX_SIDE.items():
        if stem.startswith(prefix):
            return side
    return 720


def _clear_edge_background(im: Image.Image, tolerance: int = 24) -> Image.Image:
    """Make a flat near-white background transparent by flood-filling from the edges.

    Only pixels connected to the border are cleared, so white parts inside the outline (Lumi's body) stay.
    """
    im = im.convert("RGBA")
    w, h = im.size
    px = im.load()
    seen = bytearray(w * h)
    queue = deque((x, y) for x in range(w) for y in (0, h - 1))
    queue.extend((x, y) for y in range(h) for x in (0, w - 1))
    while queue:
        x, y = queue.popleft()
        i = y * w + x
        if seen[i]:
            continue
        seen[i] = 1
        r, g, b, _ = px[x, y]
        if min(r, g, b) < 255 - tolerance:
            continue
        px[x, y] = (r, g, b, 0)
        if x > 0:
            queue.append((x - 1, y))
        if x < w - 1:
            queue.append((x + 1, y))
        if y > 0:
            queue.append((x, y - 1))
        if y < h - 1:
            queue.append((x, y + 1))
    return im


def build(src: Path) -> str:
    stem = src.stem
    im = Image.open(src)
    background = "background" in stem
    if background:
        im = im.convert("RGB")
    else:
        if im.mode != "RGBA" or im.getchannel("A").getextrema()[0] == 255:
            im = _clear_edge_background(im)  # a sprite delivered without transparency (e.g. lumi_happy)
        im = im.convert("RGBA")
        box = im.getchannel("A").getbbox()
        if box:
            im = im.crop(box)  # trim empty margins so layout percentages match what you see
    im.thumbnail((_max_side(stem), _max_side(stem)), Image.LANCZOS)
    OUT.mkdir(parents=True, exist_ok=True)
    im.save(OUT / f"{stem}.webp", "WEBP", quality=QUALITY, method=6)
    return stem


def main() -> None:
    names = [build(p) for p in sorted(SRC.glob("*.png"))]
    lines = ",\n".join(f'  "{n}"' for n in names)
    MANIFEST.write_text(
        "// Generated by scripts/town_art.py: the town art files in frontend/public/assets/town/. Do not edit.\n"
        f"export const TOWN_ART_FILES: ReadonlySet<string> = new Set([\n{lines},\n]);\n",
        encoding="utf-8",
    )
    total = sum(f.stat().st_size for f in OUT.glob("*.webp"))
    print(f"{len(names)} images -> {OUT.relative_to(ROOT)} ({total / 1e6:.1f} MB)")


if __name__ == "__main__":
    main()
